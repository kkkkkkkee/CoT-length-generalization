"""Run one routing experiment with controlled training pair exposure.

This wrapper deliberately leaves the historical routing runner untouched.  In
``balanced`` mode it replaces only the *training-pool* call to ``Task.generate``
with a variable-chain sampler whose second-query query/key pairs are scheduled
without replacement.  Evaluation panels continue to use the original uniform
generator.  All training, checkpoint, and audit logic remains in
``routing_experiment.py``.

The controlled sampler keeps the task semantics unchanged: variables are
distinct within a trace, actions and initial states are sampled independently,
and states are generated by the task's action table.  It is intended to test
whether more even query-key exposure can account for gains otherwise attributed
to parameter tying or ID augmentation.  It is not a permutation-invariant
training objective.
"""
from __future__ import annotations

import argparse
import sys
from typing import Optional

import torch

from data import Task
from routing_experiment import parse_args, run_experiment


def _balanced_variables(batch: int, length: int, nvars: int,
                        generator: Optional[torch.Generator],
                        device: torch.device) -> torch.Tensor:
    """Construct distinct variable chains with balanced second-query pairs.

    The attention runner supervises the second answer by default.  Its query
    variable is ``variables[:, 1]``; Q44 sees ``variables[:, 0]`` and Q43 sees
    the source variables at positions 0..L-1.  For every query variable, the
    first three source slots therefore cycle through distinct nonmatching IDs.
    The schedule makes those exposures nearly uniform over the generated pool,
    while a random completion fills later chain slots without replacement.
    """
    if batch < 1 or length < 2 or nvars < max(length + 1, 5):
        raise ValueError("balanced sampler requires batch>=1, length>=2, nvars>=max(length+1,5)")
    if generator is None:
        generator = torch.Generator(device=device)
    # Query variables cycle through the vocabulary.  For each query, the
    # three visible source slots use a different cyclic offset, preventing
    # repeated Q43/Q44 off-diagonal pairs within a trace.
    indices = torch.arange(batch, device=device, dtype=torch.long)
    query = (indices % nvars) + 1
    repeat = torch.div(indices, nvars, rounding_mode="floor")
    # Work modulo nvars-1 in offset space, then add one.  This guarantees
    # nonzero, distinct offsets even after many pool cycles; adding a nonzero
    # offset modulo nvars therefore cannot map a source back to its query.
    offsets = torch.stack(((3 * repeat + 1) % (nvars - 1),
                           (3 * repeat + 2) % (nvars - 1),
                           (3 * repeat + 3) % (nvars - 1)), dim=1) + 1
    source = ((query[:, None] - 1 + offsets) % nvars) + 1
    variables = torch.empty((batch, length + 1), dtype=torch.long, device=device)
    variables[:, 1] = query
    variables[:, 0] = source[:, 0]
    if length >= 3:
        variables[:, 2] = source[:, 1]
    if length >= 4:
        variables[:, 3] = source[:, 2]
    # Fill any remaining positions with a random permutation of valid IDs not
    # already used.  A small Python loop is acceptable here: generation occurs
    # once per run and the training pool is at most O(1e4) examples.
    if length + 1 > 4:
        for row in range(batch):
            used = set(int(x) for x in variables[row, :4].tolist())
            available = torch.tensor([x for x in range(1, nvars + 1)
                                      if x not in used], dtype=torch.long,
                                     device=device)
            order = torch.randperm(len(available), generator=generator,
                                   device=device)
            variables[row, 4:] = available[order[:length - 3]]
    # Ensure every row is a valid permutation prefix.  This also catches the
    # small-nvars collision case rather than silently changing semantics.
    if bool((variables[:, :, None] == variables[:, None, :]).sum(-1).gt(1).any()):
        raise RuntimeError("balanced variable sampler produced duplicate IDs")
    return variables


def balanced_generate(task: Task, batch: int, length: int,
                      generator: Optional[torch.Generator] = None,
                      device="cpu"):
    """Task.generate-compatible balanced sampler."""
    if not isinstance(task, Task):
        raise TypeError("task must be a Task")
    target_device = torch.device(device)
    sample_device = torch.device(generator.device if generator is not None
                                 else target_device)
    variables = _balanced_variables(batch, length, task.nvars, generator,
                                    sample_device)
    actions = torch.randint(task.nactions, (batch, length), generator=generator,
                            device=sample_device)
    states = torch.empty((batch, length + 1), dtype=torch.long, device=sample_device)
    states[:, 0] = torch.randint(task.nstates, (batch,), generator=generator,
                                 device=sample_device)
    table = task.action_table.to(sample_device)
    for step in range(length):
        states[:, step + 1] = table[actions[:, step], states[:, step]]
    clauses = torch.zeros((batch, 2 * length + 1, 5), dtype=torch.long,
                          device=sample_device)
    clauses[:, :length, 0] = variables[:, 1:]
    clauses[:, :length, 1] = actions + task.action_offset
    clauses[:, :length, 2] = variables[:, :-1]
    clauses[:, length:, 3] = variables
    clauses[:, length:, 4] = states + task.value_offset
    sample = {"clauses": clauses, "variables": variables,
              "actions": actions, "states": states}
    return {key: value.to(target_device) for key, value in sample.items()}


def main(argv=None):
    # Parse the wrapper-only option first, then let the historical runner parse
    # its unchanged argument surface.  This keeps old campaign manifests and
    # source hashes intact.
    wrapper = argparse.ArgumentParser(add_help=False)
    wrapper.add_argument('--coverage-mode', choices=['uniform', 'balanced'],
                         default='uniform')
    wrapper_args, remaining = wrapper.parse_known_args(argv)
    # ``--help`` is handled by the original runner as usual.
    old_argv = sys.argv
    sys.argv = [old_argv[0], *remaining]
    try:
        args = parse_args()
    finally:
        sys.argv = old_argv
    args.coverage_mode = wrapper_args.coverage_mode
    if wrapper_args.coverage_mode == 'uniform':
        return run_experiment(args)

    original_generate = Task.generate
    used_training_pool = False
    expected_length = args.length
    expected_pool = max(args.samples, args.pool_samples)

    def patched_generate(self, batch, length, generator=None, device='cpu'):
        nonlocal used_training_pool
        if (not used_training_pool and batch == expected_pool
                and length == expected_length):
            used_training_pool = True
            return balanced_generate(self, batch, length, generator, device)
        return original_generate(self, batch, length, generator, device)

    Task.generate = patched_generate
    try:
        result = run_experiment(args)
    finally:
        Task.generate = original_generate
    if not used_training_pool:
        raise RuntimeError('balanced mode did not intercept the training pool')
    return result


if __name__ == '__main__':
    main()

